def test_upstream_warning_filter_matches_only_the_full_message() -> None:
    fields = UPSTREAM_WARNING_POLICY_FILTER.split(":")

    assert len(fields) == 4
    assert fields[1] == UPSTREAM_WARNING_MESSAGE_PATTERN
    assert fields[2] == UPSTREAM_WARNING_CATEGORY == "DeprecationWarning"
    assert fields[3] == UPSTREAM_WARNING_MODULE_PATTERN
    assert fields[3] == r"^gpt_researcher\.scraper\.arxiv\.arxiv$"
    assert r"\x3a" in fields[1]
    assert ":" not in fields[1]
    assert re.fullmatch(fields[1], UPSTREAM_WARNING_MESSAGE)
    assert not re.fullmatch(fields[1], UPSTREAM_WARNING_MESSAGE + " unexpected suffix")
    assert not re.fullmatch(
        fields[1],
        UPSTREAM_WARNING_MESSAGE.replace("sunset", "deprecated"),
    )


def test_required_security_pins_are_part_of_the_contract() -> None:
    assert REQUIRED_SECURITY_CONSTRAINTS == set(SECURITY_FIXTURE_PINS)
    required_flags = {
        "--allow-unsafe",
        f"--constraint={SECURITY_CONSTRAINTS_FILE}",
        f"--constraint={COMPATIBILITY_CONSTRAINTS_FILE}",
    }
    assert all(required_flags <= set(shlex.split(command)) for command in LOCK_COMMANDS.values())
    assert all("--upgrade" not in shlex.split(command) for command in LOCK_COMMANDS.values())
    assert REQUIRED_UNSAFE_PINS == {
        filename: frozenset(pin.split("==", 1)[0] for pin in pins)
        for filename, pins in LOCK_UNSAFE_PINS.items()
    }
    assert "--generate-hashes" in shlex.split(
        LOCK_COMMANDS["requirements-container.txt"]
    )
    assert all(
        "--generate-hashes" not in shlex.split(command)
        for filename, command in LOCK_COMMANDS.items()
        if filename != "requirements-container.txt"
    )



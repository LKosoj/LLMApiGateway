def _lock_header() -> str:
    return "\n".join(
        (
            "#",
            "# This file is autogenerated by pip-compile with Python 3.12",
            "# by the following command:",
            "#",
            f"#    {COMPILE_SCRIPT_COMMAND}",
            "#",
        )
    )


def _hashed_lock_lines(pins: list[str]) -> list[str]:
    digest = "0" * 64
    lines: list[str] = []
    for pin in pins:
        lines.extend((f"{pin} \\", f"    --hash=sha256:{digest}"))
    return lines



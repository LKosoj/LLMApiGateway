def test_compile_runs_canonical_commands_in_dependency_order(tmp_path: Path, monkeypatch) -> None:
    _write_contract_fixture(tmp_path)
    calls: list[tuple[list[str], Path, bool, dict[str, str]]] = []

    def fake_run(argv, *, cwd, check, env):
        calls.append((argv, cwd, check, env))

    monkeypatch.setattr(dependency_contract.subprocess, "run", fake_run)

    compile_requirement_locks(
        tmp_path,
        pip_compile_executable="/tools/pip-compile",
    )

    expected_argv = []
    for command in LOCK_COMMANDS.values():
        argv = shlex.split(command)
        argv[0] = "/tools/pip-compile"
        expected_argv.append(argv)
    assert [call[0] for call in calls] == expected_argv
    assert all(call[1:3] == (tmp_path, True) for call in calls)
    assert all(call[3]["CUSTOM_COMPILE_COMMAND"] == COMPILE_SCRIPT_COMMAND for call in calls)


def test_bootstrap_compile_uses_source_only_temporary_root(
    tmp_path: Path,
    monkeypatch,
) -> None:
    _write_contract_fixture(tmp_path)
    original_locks = {
        filename: (tmp_path / filename).read_text(encoding="utf-8")
        for filename in LOCK_COMMANDS
    }
    calls: list[tuple[Path, str | None]] = []

    def fake_compile(root: Path, *, pip_compile_executable: str | None = None) -> None:
        calls.append((root, pip_compile_executable))
        assert root != tmp_path
        assert all((root / filename).is_file() for filename in BOOTSTRAP_SOURCE_FILES)
        assert (root / "llm_gateway_core" / "version.py").read_text(
            encoding="utf-8"
        ) == (tmp_path / "llm_gateway_core" / "version.py").read_text(encoding="utf-8")
        assert all(not (root / filename).exists() for filename in LOCK_COMMANDS)

    monkeypatch.setattr(dependency_contract, "compile_requirement_locks", fake_compile)

    verify_bootstrap_compilation(
        tmp_path,
        pip_compile_executable="/tools/pip-compile",
    )

    assert len(calls) == 1
    assert calls[0][1] == "/tools/pip-compile"
    assert {
        filename: (tmp_path / filename).read_text(encoding="utf-8")
        for filename in LOCK_COMMANDS
    } == original_locks


